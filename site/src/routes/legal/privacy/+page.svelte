<h2 id="security">Security</h2>
It is your responsibility not to save sensitive information e.g. your passwords as a part of a highlight.<br />Your
saves are ordinary bookmarks, so anyone with access to your browser profile, and every device your browser syncs
bookmarks to, can see them.<br />When you delete a save, its bookmark is deleted. To remove everything Faro stored,
delete the Faro bookmarks folder and uninstall the extension.
