<h2 id="overview">Overview</h2>
<p>
  Faro has no user accounts and no server. Everything you save with Faro stays in your browser: in your
  browser's bookmarks and in the extension's local storage. Faro does not upload your saves or any personal
  information to me or to anyone else. No data is shared with, and in particular not sold to, external parties.
</p>
<p>
  If you have turned on bookmark sync in your browser (for example Chrome sync with your Google account), your
  browser copies your bookmarks, including the ones Faro creates, to your other devices. That sync is provided by
  your browser vendor under their own privacy policy, not by Faro.
</p>
